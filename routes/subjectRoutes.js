const express = require("express");

const {
    getSubjects,
    getSubjectById,
    createSubject,
    updateSubject,
    deleteSubject
} = require("../controllers/subjectController");

const authMiddleware = require("../middleware/authMiddleware");

const router = express.Router();

/*
|--------------------------------------------------------------------------
| SUBJECT ROUTES
|--------------------------------------------------------------------------
| Base URL:
| /api/subjects
|--------------------------------------------------------------------------
*/


/*
|--------------------------------------------------------------------------
| GET ALL SUBJECTS
|--------------------------------------------------------------------------
| GET /api/subjects
|--------------------------------------------------------------------------
*/

router.get(
    "/",
    authMiddleware,
    getSubjects
);


/*
|--------------------------------------------------------------------------
| GET SUBJECT BY ID
|--------------------------------------------------------------------------
| GET /api/subjects/:id
|--------------------------------------------------------------------------
*/

router.get(
    "/:id",
    authMiddleware,
    getSubjectById
);


/*
|--------------------------------------------------------------------------
| CREATE SUBJECT
|--------------------------------------------------------------------------
| POST /api/subjects
|--------------------------------------------------------------------------
*/

router.post(
    "/",
    authMiddleware,
    createSubject
);


/*
|--------------------------------------------------------------------------
| UPDATE SUBJECT
|--------------------------------------------------------------------------
| PUT /api/subjects/:id
|--------------------------------------------------------------------------
*/

router.put(
    "/:id",
    authMiddleware,
    updateSubject
);


/*
|--------------------------------------------------------------------------
| DELETE SUBJECT
|--------------------------------------------------------------------------
| DELETE /api/subjects/:id
|--------------------------------------------------------------------------
*/

router.delete(
    "/:id",
    authMiddleware,
    deleteSubject
);


/*
|--------------------------------------------------------------------------
| EXPORT ROUTER
|--------------------------------------------------------------------------
*/

module.exports = router;