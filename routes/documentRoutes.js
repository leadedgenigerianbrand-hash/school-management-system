"use strict";

const express = require("express");

const {
    create,
    getById,
    getStudentDocuments,
    getAll,
    update,
    remove,
    search,
    count,
    types
} = require("../controllers/documentController");

const authMiddleware =
    require("../middleware/authMiddleware");

const router =
    express.Router();

/*
|--------------------------------------------------------------------------
| DOCUMENT ROUTES
|--------------------------------------------------------------------------
|
| Base URL:
| /api/documents
|
| All document routes require authentication.
|
|--------------------------------------------------------------------------
*/

router.use(authMiddleware);

/*
|--------------------------------------------------------------------------
| DOCUMENT COUNT
|--------------------------------------------------------------------------
|
| GET /api/documents/count
|
| Returns the number of documents belonging to the
| authenticated user's school.
|
|--------------------------------------------------------------------------
*/

router.get(
    "/count",
    count
);

/*
|--------------------------------------------------------------------------
| DOCUMENT TYPES
|--------------------------------------------------------------------------
|
| GET /api/documents/types
|
| Returns distinct document types used by the
| authenticated user's school.
|
|--------------------------------------------------------------------------
*/

router.get(
    "/types",
    types
);

/*
|--------------------------------------------------------------------------
| SEARCH DOCUMENTS
|--------------------------------------------------------------------------
|
| GET /api/documents/search?q=
|
| Searches documents using document information
| and student information.
|
|--------------------------------------------------------------------------
*/

router.get(
    "/search",
    search
);

/*
|--------------------------------------------------------------------------
| STUDENT DOCUMENTS
|--------------------------------------------------------------------------
|
| GET /api/documents/student/:studentId
|
| Returns documents belonging to one student.
|
|--------------------------------------------------------------------------
*/

router.get(
    "/student/:studentId",
    getStudentDocuments
);

/*
|--------------------------------------------------------------------------
| ALL SCHOOL DOCUMENTS
|--------------------------------------------------------------------------
|
| GET /api/documents
|
| Optional query parameters:
|
| documentType
| limit
| offset
|
|--------------------------------------------------------------------------
*/

router.get(
    "/",
    getAll
);

/*
|--------------------------------------------------------------------------
| DOCUMENT BY ID
|--------------------------------------------------------------------------
|
| GET /api/documents/:id
|
|--------------------------------------------------------------------------
*/

router.get(
    "/:id",
    getById
);

/*
|--------------------------------------------------------------------------
| CREATE DOCUMENT
|--------------------------------------------------------------------------
|
| POST /api/documents
|
|--------------------------------------------------------------------------
*/

router.post(
    "/",
    create
);

/*
|--------------------------------------------------------------------------
| UPDATE DOCUMENT
|--------------------------------------------------------------------------
|
| PUT /api/documents/:id
|
|--------------------------------------------------------------------------
*/

router.put(
    "/:id",
    update
);

/*
|--------------------------------------------------------------------------
| DELETE DOCUMENT
|--------------------------------------------------------------------------
|
| DELETE /api/documents/:id
|
|--------------------------------------------------------------------------
*/

router.delete(
    "/:id",
    remove
);

/*
|--------------------------------------------------------------------------
| EXPORT ROUTER
|--------------------------------------------------------------------------
*/

module.exports = router;