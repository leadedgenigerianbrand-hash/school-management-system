const express = require("express");

const {
    create,
    getById,
    getStudentDocuments,
    getAll,
    update,
    remove,
    search,
    count,
    types
} = require("../controllers/documentController");

const authMiddleware = require("../middleware/authMiddleware");

const router = express.Router();

/*
|--------------------------------------------------------------------------
| DOCUMENT ROUTES
|--------------------------------------------------------------------------
| Base URL: /api/documents
|--------------------------------------------------------------------------
*/


/*
|--------------------------------------------------------------------------
| GET DOCUMENT COUNT
|--------------------------------------------------------------------------
| GET /api/documents/count
|--------------------------------------------------------------------------
*/

router.get(
    "/count",
    authMiddleware,
    count
);


/*
|--------------------------------------------------------------------------
| GET DOCUMENT TYPES
|--------------------------------------------------------------------------
| GET /api/documents/types
|--------------------------------------------------------------------------
*/

router.get(
    "/types",
    authMiddleware,
    types
);


/*
|--------------------------------------------------------------------------
| SEARCH DOCUMENTS
|--------------------------------------------------------------------------
| GET /api/documents/search?q=
|--------------------------------------------------------------------------
*/

router.get(
    "/search",
    authMiddleware,
    search
);


/*
|--------------------------------------------------------------------------
| GET STUDENT DOCUMENTS
|--------------------------------------------------------------------------
| GET /api/documents/student/:studentId
|--------------------------------------------------------------------------
*/

router.get(
    "/student/:studentId",
    authMiddleware,
    getStudentDocuments
);


/*
|--------------------------------------------------------------------------
| GET ALL DOCUMENTS
|--------------------------------------------------------------------------
| GET /api/documents
|--------------------------------------------------------------------------
*/

router.get(
    "/",
    authMiddleware,
    getAll
);


/*
|--------------------------------------------------------------------------
| GET DOCUMENT BY ID
|--------------------------------------------------------------------------
| GET /api/documents/:id
|--------------------------------------------------------------------------
*/

router.get(
    "/:id",
    authMiddleware,
    getById
);


/*
|--------------------------------------------------------------------------
| CREATE DOCUMENT
|--------------------------------------------------------------------------
| POST /api/documents
|--------------------------------------------------------------------------
*/

router.post(
    "/",
    authMiddleware,
    create
);


/*
|--------------------------------------------------------------------------
| UPDATE DOCUMENT
|--------------------------------------------------------------------------
| PUT /api/documents/:id
|--------------------------------------------------------------------------
*/

router.put(
    "/:id",
    authMiddleware,
    update
);


/*
|--------------------------------------------------------------------------
| DELETE DOCUMENT
|--------------------------------------------------------------------------
| DELETE /api/documents/:id
|--------------------------------------------------------------------------
*/

router.delete(
    "/:id",
    authMiddleware,
    remove
);


/*
|--------------------------------------------------------------------------
| EXPORT ROUTER
|--------------------------------------------------------------------------
*/

module.exports = router;