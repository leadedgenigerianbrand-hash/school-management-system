const express = require("express");

const router = express.Router();


/*
|--------------------------------------------------------------------------
| AUTHENTICATION MIDDLEWARE
|--------------------------------------------------------------------------
*/

const authMiddleware =
    require("../middleware/authMiddleware");


const authenticate =
    typeof authMiddleware === "function"
        ? authMiddleware
        : authMiddleware.authenticate;


/*
|--------------------------------------------------------------------------
| VALIDATE AUTHENTICATION MIDDLEWARE
|--------------------------------------------------------------------------
*/

if (typeof authenticate !== "function") {

    throw new TypeError(
        "Authentication middleware is not exported correctly from middleware/authMiddleware.js"
    );

}


/*
|--------------------------------------------------------------------------
| CLASS CONTROLLER
|--------------------------------------------------------------------------
*/

const classController =
    require("../controllers/classController");


const {
    create,
    getAll,
    getById,
    update,
    remove,
    search
} = classController;


/*
|--------------------------------------------------------------------------
| VALIDATE CLASS CONTROLLER
|--------------------------------------------------------------------------
*/

const controllerFunctions = {

    create,

    getAll,

    getById,

    update,

    remove,

    search

};


for (
    const [name, handler]
    of Object.entries(controllerFunctions)
) {

    if (typeof handler !== "function") {

        throw new TypeError(
            `Class controller "${name}" is not exported as a function.`
        );

    }

}


/*
|--------------------------------------------------------------------------
| CLASS ROUTES
|--------------------------------------------------------------------------
|
| Base URL:
|
| /api/classes
|
|--------------------------------------------------------------------------
*/


/*
|--------------------------------------------------------------------------
| SEARCH CLASSES
|--------------------------------------------------------------------------
|
| GET /api/classes/search?q=
|
|--------------------------------------------------------------------------
*/

router.get(
    "/search",
    authenticate,
    search
);


/*
|--------------------------------------------------------------------------
| GET ALL CLASSES
|--------------------------------------------------------------------------
|
| GET /api/classes
|
|--------------------------------------------------------------------------
*/

router.get(
    "/",
    authenticate,
    getAll
);


/*
|--------------------------------------------------------------------------
| GET CLASS BY ID
|--------------------------------------------------------------------------
|
| GET /api/classes/:id
|
|--------------------------------------------------------------------------
*/

router.get(
    "/:id",
    authenticate,
    getById
);


/*
|--------------------------------------------------------------------------
| CREATE CLASS
|--------------------------------------------------------------------------
|
| POST /api/classes
|
|--------------------------------------------------------------------------
*/

router.post(
    "/",
    authenticate,
    create
);


/*
|--------------------------------------------------------------------------
| UPDATE CLASS
|--------------------------------------------------------------------------
|
| PUT /api/classes/:id
|
|--------------------------------------------------------------------------
*/

router.put(
    "/:id",
    authenticate,
    update
);


/*
|--------------------------------------------------------------------------
| DELETE CLASS
|--------------------------------------------------------------------------
|
| DELETE /api/classes/:id
|
|--------------------------------------------------------------------------
*/

router.delete(
    "/:id",
    authenticate,
    remove
);


/*
|--------------------------------------------------------------------------
| EXPORT ROUTER
|--------------------------------------------------------------------------
*/

module.exports = router;