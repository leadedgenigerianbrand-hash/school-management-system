const express = require("express");

const {
    getDashboardReport,
    getStudentReport,
    getAcademicReport,
    getAttendanceReport,
    getFeeReport,
    getStaffReport
} = require("../controllers/reportController");

const authMiddleware = require("../middleware/authMiddleware");

const router = express.Router();

/*
|--------------------------------------------------------------------------
| REPORT ROUTES
|--------------------------------------------------------------------------
| Base URL:
| /api/reports
|--------------------------------------------------------------------------
*/


/*
|--------------------------------------------------------------------------
| DASHBOARD REPORT
|--------------------------------------------------------------------------
| GET /api/reports/dashboard
|--------------------------------------------------------------------------
*/

router.get(
    "/dashboard",
    authMiddleware,
    getDashboardReport
);


/*
|--------------------------------------------------------------------------
| STUDENT REPORT
|--------------------------------------------------------------------------
| GET /api/reports/students
|--------------------------------------------------------------------------
*/

router.get(
    "/students",
    authMiddleware,
    getStudentReport
);


/*
|--------------------------------------------------------------------------
| ACADEMIC REPORT
|--------------------------------------------------------------------------
| GET /api/reports/academic
|--------------------------------------------------------------------------
*/

router.get(
    "/academic",
    authMiddleware,
    getAcademicReport
);


/*
|--------------------------------------------------------------------------
| ATTENDANCE REPORT
|--------------------------------------------------------------------------
| GET /api/reports/attendance
|--------------------------------------------------------------------------
*/

router.get(
    "/attendance",
    authMiddleware,
    getAttendanceReport
);


/*
|--------------------------------------------------------------------------
| FEE REPORT
|--------------------------------------------------------------------------
| GET /api/reports/fees
|--------------------------------------------------------------------------
*/

router.get(
    "/fees",
    authMiddleware,
    getFeeReport
);


/*
|--------------------------------------------------------------------------
| STAFF REPORT
|--------------------------------------------------------------------------
| GET /api/reports/staff
|--------------------------------------------------------------------------
*/

router.get(
    "/staff",
    authMiddleware,
    getStaffReport
);


/*
|--------------------------------------------------------------------------
| EXPORT ROUTER
|--------------------------------------------------------------------------
*/

module.exports = router;