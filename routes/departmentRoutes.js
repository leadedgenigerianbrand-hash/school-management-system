const express = require("express");

const {
    create,
    getById,
    getAll,
    update,
    remove,
    search
} = require("../controllers/departmentController");

const authMiddleware = require("../middleware/authMiddleware");

const router = express.Router();

/*
|--------------------------------------------------------------------------
| DEPARTMENT ROUTES
|--------------------------------------------------------------------------
| Base URL: /api/departments
|--------------------------------------------------------------------------
*/


/*
|--------------------------------------------------------------------------
| GET ALL DEPARTMENTS
|--------------------------------------------------------------------------
| GET /api/departments
|--------------------------------------------------------------------------
*/

router.get(
    "/",
    authMiddleware,
    getAll
);


/*
|--------------------------------------------------------------------------
| SEARCH DEPARTMENTS
|--------------------------------------------------------------------------
| GET /api/departments/search?q=
|--------------------------------------------------------------------------
*/

router.get(
    "/search",
    authMiddleware,
    search
);


/*
|--------------------------------------------------------------------------
| GET DEPARTMENT BY ID
|--------------------------------------------------------------------------
| GET /api/departments/:id
|--------------------------------------------------------------------------
*/

router.get(
    "/:id",
    authMiddleware,
    getById
);


/*
|--------------------------------------------------------------------------
| CREATE DEPARTMENT
|--------------------------------------------------------------------------
| POST /api/departments
|--------------------------------------------------------------------------
*/

router.post(
    "/",
    authMiddleware,
    create
);


/*
|--------------------------------------------------------------------------
| UPDATE DEPARTMENT
|--------------------------------------------------------------------------
| PUT /api/departments/:id
|--------------------------------------------------------------------------
*/

router.put(
    "/:id",
    authMiddleware,
    update
);


/*
|--------------------------------------------------------------------------
| DELETE DEPARTMENT
|--------------------------------------------------------------------------
| DELETE /api/departments/:id
|--------------------------------------------------------------------------
*/

router.delete(
    "/:id",
    authMiddleware,
    remove
);


/*
|--------------------------------------------------------------------------
| EXPORT ROUTER
|--------------------------------------------------------------------------
*/

module.exports = router;