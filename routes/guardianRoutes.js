const express = require("express");

const router = express.Router();

const authMiddleware =
    require("../middleware/authMiddleware");

const {
    createGuardian,
    getGuardians,
    getGuardianById,
    updateGuardian,
    deleteGuardian,
    searchGuardians,
    getGuardiansByStudent
} = require("../controllers/guardianController");


/*
|--------------------------------------------------------------------------
| GUARDIAN ROUTES
|--------------------------------------------------------------------------
|
| Base URL:
| /api/guardians
|
|--------------------------------------------------------------------------
*/


/*
|--------------------------------------------------------------------------
| AUTHENTICATION
|--------------------------------------------------------------------------
|
| All guardian routes require authentication.
|
|--------------------------------------------------------------------------
*/

router.use(
    authMiddleware
);


/*
|--------------------------------------------------------------------------
| SEARCH GUARDIANS
|--------------------------------------------------------------------------
|
| GET /api/guardians/search?q=
|
|--------------------------------------------------------------------------
*/

router.get(
    "/search",
    searchGuardians
);


/*
|--------------------------------------------------------------------------
| GET GUARDIANS BY STUDENT
|--------------------------------------------------------------------------
|
| GET /api/guardians/student/:studentId
|
|--------------------------------------------------------------------------
*/

router.get(
    "/student/:studentId",
    getGuardiansByStudent
);


/*
|--------------------------------------------------------------------------
| GET ALL GUARDIANS
|--------------------------------------------------------------------------
|
| GET /api/guardians
|
|--------------------------------------------------------------------------
*/

router.get(
    "/",
    getGuardians
);


/*
|--------------------------------------------------------------------------
| CREATE GUARDIAN
|--------------------------------------------------------------------------
|
| POST /api/guardians
|
|--------------------------------------------------------------------------
*/

router.post(
    "/",
    createGuardian
);


/*
|--------------------------------------------------------------------------
| GET GUARDIAN BY ID
|--------------------------------------------------------------------------
|
| GET /api/guardians/:id
|
|--------------------------------------------------------------------------
*/

router.get(
    "/:id",
    getGuardianById
);


/*
|--------------------------------------------------------------------------
| UPDATE GUARDIAN
|--------------------------------------------------------------------------
|
| PUT /api/guardians/:id
|
|--------------------------------------------------------------------------
*/

router.put(
    "/:id",
    updateGuardian
);


/*
|--------------------------------------------------------------------------
| DELETE GUARDIAN
|--------------------------------------------------------------------------
|
| DELETE /api/guardians/:id
|
|--------------------------------------------------------------------------
*/

router.delete(
    "/:id",
    deleteGuardian
);


/*
|--------------------------------------------------------------------------
| EXPORT ROUTER
|--------------------------------------------------------------------------
*/

module.exports = router;