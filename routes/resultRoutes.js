const express = require("express");

const {
    createResult,
    getResultById,
    getStudentResults,
    getClassResults,
    getSubjectResults,
    updateResult,
    deleteResult,
    approveResult,
    searchResults,
    getResultStatistics
} = require("../controllers/resultController");

const authMiddleware = require("../middleware/authMiddleware");

const router = express.Router();

/*
|--------------------------------------------------------------------------
| RESULT ROUTES
|--------------------------------------------------------------------------
| Base URL: /api/results
|--------------------------------------------------------------------------
*/


/*
|--------------------------------------------------------------------------
| RESULT STATISTICS
|--------------------------------------------------------------------------
| GET /api/results/statistics
|--------------------------------------------------------------------------
*/

router.get(
    "/statistics",
    authMiddleware,
    getResultStatistics
);


/*
|--------------------------------------------------------------------------
| SEARCH RESULTS
|--------------------------------------------------------------------------
| GET /api/results/search?q=
|--------------------------------------------------------------------------
*/

router.get(
    "/search",
    authMiddleware,
    searchResults
);


/*
|--------------------------------------------------------------------------
| STUDENT RESULTS
|--------------------------------------------------------------------------
| GET /api/results/student/:studentId
|--------------------------------------------------------------------------
*/

router.get(
    "/student/:studentId",
    authMiddleware,
    getStudentResults
);


/*
|--------------------------------------------------------------------------
| CLASS RESULTS
|--------------------------------------------------------------------------
| GET /api/results/class/:classId
|--------------------------------------------------------------------------
*/

router.get(
    "/class/:classId",
    authMiddleware,
    getClassResults
);


/*
|--------------------------------------------------------------------------
| SUBJECT RESULTS
|--------------------------------------------------------------------------
| GET /api/results/subject/:subjectId
|--------------------------------------------------------------------------
*/

router.get(
    "/subject/:subjectId",
    authMiddleware,
    getSubjectResults
);


/*
|--------------------------------------------------------------------------
| GET RESULT BY ID
|--------------------------------------------------------------------------
| GET /api/results/:id
|--------------------------------------------------------------------------
*/

router.get(
    "/:id",
    authMiddleware,
    getResultById
);


/*
|--------------------------------------------------------------------------
| CREATE RESULT
|--------------------------------------------------------------------------
| POST /api/results
|--------------------------------------------------------------------------
*/

router.post(
    "/",
    authMiddleware,
    createResult
);


/*
|--------------------------------------------------------------------------
| UPDATE RESULT
|--------------------------------------------------------------------------
| PUT /api/results/:id
|--------------------------------------------------------------------------
*/

router.put(
    "/:id",
    authMiddleware,
    updateResult
);


/*
|--------------------------------------------------------------------------
| APPROVE RESULT
|--------------------------------------------------------------------------
| PATCH /api/results/:id/approve
|--------------------------------------------------------------------------
*/

router.patch(
    "/:id/approve",
    authMiddleware,
    approveResult
);


/*
|--------------------------------------------------------------------------
| DELETE RESULT
|--------------------------------------------------------------------------
| DELETE /api/results/:id
|--------------------------------------------------------------------------
*/

router.delete(
    "/:id",
    authMiddleware,
    deleteResult
);


/*
|--------------------------------------------------------------------------
| EXPORT ROUTER
|--------------------------------------------------------------------------
*/

module.exports = router;