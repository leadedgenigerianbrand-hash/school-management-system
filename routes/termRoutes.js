const express = require("express");

const {
    getTerms,
    getTermById,
    createTerm,
    updateTerm,
    deleteTerm
} = require("../controllers/termController");

const authMiddleware = require("../middleware/authMiddleware");

const router = express.Router();

/*
|--------------------------------------------------------------------------
| TERM ROUTES
|--------------------------------------------------------------------------
| Base URL:
| /api/terms
|--------------------------------------------------------------------------
*/


/*
|--------------------------------------------------------------------------
| GET ALL TERMS
|--------------------------------------------------------------------------
| GET /api/terms
|--------------------------------------------------------------------------
*/

router.get(
    "/",
    authMiddleware,
    getTerms
);


/*
|--------------------------------------------------------------------------
| GET TERM BY ID
|--------------------------------------------------------------------------
| GET /api/terms/:id
|--------------------------------------------------------------------------
*/

router.get(
    "/:id",
    authMiddleware,
    getTermById
);


/*
|--------------------------------------------------------------------------
| CREATE TERM
|--------------------------------------------------------------------------
| POST /api/terms
|--------------------------------------------------------------------------
*/

router.post(
    "/",
    authMiddleware,
    createTerm
);


/*
|--------------------------------------------------------------------------
| UPDATE TERM
|--------------------------------------------------------------------------
| PUT /api/terms/:id
|--------------------------------------------------------------------------
*/

router.put(
    "/:id",
    authMiddleware,
    updateTerm
);


/*
|--------------------------------------------------------------------------
| DELETE TERM
|--------------------------------------------------------------------------
| DELETE /api/terms/:id
|--------------------------------------------------------------------------
*/

router.delete(
    "/:id",
    authMiddleware,
    deleteTerm
);


/*
|--------------------------------------------------------------------------
| EXPORT ROUTER
|--------------------------------------------------------------------------
*/

module.exports = router;